export function normalizeModuleKey(rawKey: string): ModuleKey | null {
    if (!rawKey || typeof rawKey !== 'string') return null;
    const lower = rawKey.trim().toLowerCase();
    if (MODULE_KEY_ALIASES[lower]) return MODULE_KEY_ALIASES[lower];
    const kebab = lower.replace(/[\s_]+/g, '-');
    if (MODULE_KEY_ALIASES[kebab]) return MODULE_KEY_ALIASES[kebab];
    const stripped = lower.replace(/[^a-z0-9]/g, '');
    if (MODULE_KEY_ALIASES[stripped]) return MODULE_KEY_ALIASES[stripped];
    return null;
}

